"""Embed metadata in figures and index every results folder.

New figures are tagged automatically when they are saved (project_paths.register).
This tool covers the rest:

    python common/tag_figures.py                 tag untagged figures in Results/ and rewrite the indexes
    python common/tag_figures.py --force         re-tag every figure, including ones tagged at save time
    python common/tag_figures.py --index-only    only rewrite the index README of each results folder
    python common/tag_figures.py --show FIGURE   print the metadata stored in a figure

PNG figures get PNG text chunks and HTML (plotly) figures get <meta name="mes:..."> tags
in the page head. Metadata added afterwards records what is known from the folder and
the file (experiment, producing script, dataset, file date) and says it was added
retrospectively. PDFs are not re-tagged (no PDF library in the environment); each has a
tagged PNG twin, and PDFs saved from now on carry metadata from savefig.

The PNG text chunks can be read with this script, Pillow (Image.open(p).text), exiftool,
or GIMP's image properties.
"""

from __future__ import annotations

import argparse
import datetime as dt
import html
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import figure_catalogue  # noqa: E402
import project_paths  # noqa: E402

FIGURE_SUFFIXES = {".png", ".html", ".pdf", ".svg"}
INDEX_SUFFIXES = FIGURE_SUFFIXES | {".csv", ".json", ".npz", ".txt", ".pptx"}
GENERATED_MARK = "<!-- generated by common/tag_figures.py: edit the catalogue there, not this file -->"
DEFAULT_DAY = "2013-02-21"

EXPERIMENT_TITLES = {
    "01_data_preparation": "Data preparation: LCL data exploration and the showcase dataset",
    "02_day_ahead_sharing_methods": "Day-ahead energy sharing: central vs exchange ADMM vs bilateral ADMM vs rule-based (N = 10)",
    "03_day_ahead_sensitivity": "Day-ahead sensitivity: trade fee, P2P price, ADMM rho and tolerance, Shapley allocation",
    "04_day_ahead_scaling": "Day-ahead scaling: the showcase comparison for larger communities",
    "05_realtime_methods": "Real-time execution under forecast error: open loop, fixed schedule, local re-optimisation, "
                           "rolling ADMM, rolling central",
    "06_realtime_scaling": "Real-time methods against community size (N = 5 to 1000), sequential and parallel",
    "archive": "Superseded results kept for reference",
}


# ============================================================================
# READ / WRITE METADATA
# ============================================================================
def read_png(path: Path) -> dict:
    from PIL import Image

    with Image.open(path) as image:
        return dict(getattr(image, "text", {}) or {})


def tag_png(path: Path, meta: dict) -> None:
    from PIL import Image
    from PIL.PngImagePlugin import PngInfo

    stat = path.stat()
    with Image.open(path) as image:
        image.load()
        info = PngInfo()
        merged = {**(getattr(image, "text", {}) or {}), **{k: str(v) for k, v in meta.items() if v}}
        for key, value in merged.items():
            info.add_itxt(key, value) if not value.isascii() else info.add_text(key, value)
        options = {"pnginfo": info}
        if "dpi" in image.info:
            options["dpi"] = image.info["dpi"]
        image.save(path, format="PNG", **options)
    os.utime(path, (stat.st_atime, stat.st_mtime))  # keep the original file date


_META_RE = re.compile(r'\s*<meta name="mes:[^"]*" content="[^"]*"\s*/?>', re.IGNORECASE)


def read_html(path: Path) -> dict:
    head = path.read_text(encoding="utf-8", errors="replace")[:20000]
    return {html.unescape(k): html.unescape(v)
            for k, v in re.findall(r'<meta name="mes:([^"]*)" content="([^"]*)"', head)}


def tag_html(path: Path, meta: dict, keep_date: bool = False) -> None:
    stat = path.stat()
    text = path.read_text(encoding="utf-8", errors="surrogateescape")
    text = _META_RE.sub("", text)
    tags = "".join(f'\n<meta name="mes:{html.escape(str(k))}" content="{html.escape(str(v))}">'
                   for k, v in meta.items() if v)
    match = re.search(r"<head[^>]*>", text, re.IGNORECASE)
    if match:
        text = text[: match.end()] + tags + text[match.end():]
    else:
        text = f"<head>{tags}\n</head>\n" + text
    path.write_text(text, encoding="utf-8", errors="surrogateescape")
    if keep_date:
        os.utime(path, (stat.st_atime, stat.st_mtime))


def read_metadata(path: Path) -> dict:
    if path.suffix.lower() == ".png":
        return read_png(path)
    if path.suffix.lower() == ".html":
        return read_html(path)
    return {}


# ============================================================================
# RETROSPECTIVE METADATA FROM THE FOLDER
# ============================================================================
def _context(path: Path) -> dict:
    parts = path.relative_to(project_paths.RESULTS_DIR).parts
    experiment = parts[0]
    size = next((p for p in parts if re.fullmatch(r"N\d{4}", p)), None)
    case = parts[parts.index("cases") + 1] if "cases" in parts[:-1] else None
    if experiment == "archive":
        dataset = "unknown (archived result)"
    elif size and size != "N0010":
        dataset = f"showcase_{DEFAULT_DAY}_{size} (N={int(size[1:])} buildings, T=24 h, day {DEFAULT_DAY})"
    elif experiment == "01_data_preparation" and not path.name.startswith("10_"):
        dataset = "raw LCL smart-meter and PV data"
    else:
        dataset = f"showcase_{DEFAULT_DAY} (N=10 buildings, T=24 h, day {DEFAULT_DAY})"
    return {"experiment": experiment, "dataset": dataset, "case": case}


def retro_metadata(path: Path) -> dict:
    entry = figure_catalogue.lookup(path.name)
    context = _context(path)
    created = dt.datetime.fromtimestamp(path.stat().st_mtime).astimezone().isoformat(timespec="seconds")
    return {
        "Title": entry.get("title", path.stem),
        "Description": entry.get("description", ""),
        "Experiment": context["experiment"],
        "Source": entry.get("script", "unknown"),
        "Dataset": context["dataset"],
        "Noise case": context["case"] or "",
        "Creation Time": created,
        "Metadata note": "added retrospectively by common/tag_figures.py from the folder and catalogue; "
                         "the command line and code version of the original run were not recorded",
    }


def tag_results(force: bool = False) -> None:
    counts = {"tagged": 0, "kept": 0, "pdf": 0}
    for path in sorted(project_paths.RESULTS_DIR.rglob("*")):
        suffix = path.suffix.lower()
        if not path.is_file() or suffix not in FIGURE_SUFFIXES:
            continue
        if suffix in (".pdf", ".svg"):
            counts["pdf"] += 1
            continue
        if not force and read_metadata(path).get("Experiment"):
            counts["kept"] += 1
            continue
        meta = retro_metadata(path)
        if suffix == ".png":
            tag_png(path, meta)
        else:
            tag_html(path, meta, keep_date=True)
        counts["tagged"] += 1
    print(f"tagged {counts['tagged']} figures, kept {counts['kept']} already tagged, "
          f"skipped {counts['pdf']} PDF/SVG (each has a tagged PNG twin)")


# ============================================================================
# INDEX README PER RESULTS FOLDER
# ============================================================================
def _rows(folder: Path):
    groups: dict[tuple[str, str], list[str]] = {}
    for path in sorted(folder.rglob("*")):
        if not path.is_file() or path.name.startswith(".") or path.name == "README.md":
            continue
        if path.suffix.lower() not in INDEX_SUFFIXES:
            continue
        rel_dir = path.parent.relative_to(folder).as_posix()
        stem = path.name[: -len(".results.json")] + "*" if path.name.endswith(".results.json") else path.stem
        groups.setdefault((rel_dir, stem), []).append(path.name)
    return groups


def write_index(folder: Path) -> None:
    readme = folder / "README.md"
    if readme.exists() and GENERATED_MARK not in readme.read_text(encoding="utf-8"):
        print(f"kept hand-written {project_paths.relative(readme)}")
        return
    lines = [GENERATED_MARK, "", f"# {EXPERIMENT_TITLES.get(folder.name, folder.name)}", ""]
    code = project_paths.ROOT / folder.name
    if code.is_dir():
        lines += [f"Code and method description: [`{folder.name}/`](../../{folder.name}/README.md).", ""]
    lines += [
        "Every PNG and HTML figure carries embedded metadata (title, description, experiment, producing",
        "script, dataset, creation time; command line and git commit for figures made after the",
        "reorganisation). Show it with `python common/tag_figures.py --show <figure>`.",
        "",
    ]
    current = None
    for (rel_dir, stem), names in sorted(_rows(folder).items(), key=lambda kv: (kv[0][0] != ".", kv[0])):
        if rel_dir != current:
            current = rel_dir
            heading = "This folder" if rel_dir == "." else f"`{rel_dir}/`"
            lines += ["", f"## {heading}", "", "| File | Formats | Description | Produced by |", "|---|---|---|---|"]
        entry = figure_catalogue.lookup(names[0])
        formats = ", ".join(sorted({n.split(".", 1)[1] if n.endswith(".results.json") else Path(n).suffix[1:]
                                    for n in names}))
        title = entry.get("title", "")
        description = f"**{title}.** {entry.get('description', '')}" if title else "—"
        lines.append(f"| `{stem}` | {formats} | {description} | `{entry.get('script', '—')}` |")
    readme.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {project_paths.relative(readme)}")


def write_indexes() -> None:
    for folder in sorted(project_paths.RESULTS_DIR.iterdir()):
        if folder.is_dir():
            write_index(folder)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--force", action="store_true", help="re-tag figures that already have metadata")
    parser.add_argument("--index-only", action="store_true", help="only rewrite the folder indexes")
    parser.add_argument("--show", type=Path, nargs="+", help="print the metadata of these figures")
    args = parser.parse_args()
    if args.show:
        for path in args.show:
            print(f"== {path}")
            for key, value in read_metadata(path).items():
                print(f"  {key}: {value}")
        return
    if not args.index_only:
        tag_results(force=args.force)
    write_indexes()


if __name__ == "__main__":
    main()
